-- 4. Extend SERVICE_REQUESTS with Diagnostics, Repair Actions, Estimates, and Extended Workflow Status
DECLARE
    v_count NUMBER;
BEGIN
    -- Drop legacy STATUS check constraint if present to accommodate all Phase 2B workflow states
    FOR r IN (
        SELECT constraint_name 
        FROM user_constraints 
        WHERE table_name = 'SERVICE_REQUESTS' 
          AND constraint_type = 'C' 
          AND search_condition_vc LIKE '%STATUS IN%'
    ) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE SERVICE_REQUESTS DROP CONSTRAINT ' || r.constraint_name;
    END LOOP;

    EXECUTE IMMEDIATE 'ALTER TABLE SERVICE_REQUESTS ADD CONSTRAINT CK_SR_STATUS CHECK (
        STATUS IN (
            ''REGISTERED'',
            ''ASSIGNED_TO_ASF'',
            ''ACKNOWLEDGED'',
            ''APPOINTMENT_SCHEDULED'',
            ''TECHNICIAN_CHECKED_IN'',
