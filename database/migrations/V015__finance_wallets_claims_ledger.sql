-- 13. Seed Granular Finance RBAC Permissions
MERGE INTO PERMISSIONS p
USING (
    SELECT '10000000-0000-0000-0000-000000000050' AS PERMISSION_ID, 'finance:read' AS CODE, 'FINANCE' AS MODULE, 'View financial ledgers, wallets, claims and reports' AS DESCRIPTION FROM DUAL UNION ALL
    SELECT '10000000-0000-0000-0000-000000000051' AS PERMISSION_ID, 'finance:wallets' AS CODE, 'FINANCE' AS MODULE, 'Manage brand wallets and submit top-up transactions' AS DESCRIPTION FROM DUAL UNION ALL
    SELECT '10000000-0000-0000-0000-000000000052' AS PERMISSION_ID, 'finance:claims' AS CODE, 'FINANCE' AS MODULE, 'Generate and submit monthly service labor and travel claims' AS DESCRIPTION FROM DUAL UNION ALL
    SELECT '10000000-0000-0000-0000-000000000053' AS PERMISSION_ID, 'finance:approve' AS CODE, 'FINANCE' AS MODULE, 'Authorize wallet deposits, service claim batches, and penalties' AS DESCRIPTION FROM DUAL UNION ALL
    SELECT '10000000-0000-0000-0000-000000000054' AS PERMISSION_ID, 'finance:post' AS CODE, 'FINANCE' AS MODULE, 'Post balanced journals and authorize compensating ledger reversals' AS DESCRIPTION FROM DUAL UNION ALL
    SELECT '10000000-0000-0000-0000-000000000055' AS PERMISSION_ID, 'finance:settle' AS CODE, 'FINANCE' AS MODULE, 'Execute and reconcile franchisee payout settlement batches' AS DESCRIPTION FROM DUAL
) s ON (p.CODE = s.CODE)
WHEN NOT MATCHED THEN
    INSERT (PERMISSION_ID, CODE, MODULE, DESCRIPTION)
    VALUES (s.PERMISSION_ID, s.CODE, s.MODULE, s.DESCRIPTION);

-- Assign all 6 finance permissions to ADMIN and FINANCE roles
MERGE INTO ROLE_PERMISSIONS rp
USING (
    SELECT r.ROLE_ID, p.PERMISSION_ID
    FROM ROLES r
    CROSS JOIN PERMISSIONS p
    WHERE r.CODE IN ('ADMIN', 'FINANCE')
      AND p.CODE IN ('finance:read', 'finance:wallets', 'finance:claims', 'finance:approve', 'finance:post', 'finance:settle')
) s ON (rp.ROLE_ID = s.ROLE_ID AND rp.PERMISSION_ID = s.PERMISSION_ID)
WHEN NOT MATCHED THEN INSERT (ROLE_ID, PERMISSION_ID) VALUES (s.ROLE_ID, s.PERMISSION_ID);

-- Assign finance:read and finance:wallets to BRAND role
MERGE INTO ROLE_PERMISSIONS rp
USING (
    SELECT r.ROLE_ID, p.PERMISSION_ID
    FROM ROLES r
    CROSS JOIN PERMISSIONS p
    WHERE r.CODE = 'BRAND'
      AND p.CODE IN ('finance:read', 'finance:wallets')
) s ON (rp.ROLE_ID = s.ROLE_ID AND rp.PERMISSION_ID = s.PERMISSION_ID)
WHEN NOT MATCHED THEN INSERT (ROLE_ID, PERMISSION_ID) VALUES (s.ROLE_ID, s.PERMISSION_ID);

-- Assign finance:read and finance:claims to ASF role
MERGE INTO ROLE_PERMISSIONS rp
USING (
    SELECT r.ROLE_ID, p.PERMISSION_ID
    FROM ROLES r
    CROSS JOIN PERMISSIONS p
    WHERE r.CODE = 'ASF'
      AND p.CODE IN ('finance:read', 'finance:claims')
) s ON (rp.ROLE_ID = s.ROLE_ID AND rp.PERMISSION_ID = s.PERMISSION_ID)
WHEN NOT MATCHED THEN INSERT (ROLE_ID, PERMISSION_ID) VALUES (s.ROLE_ID, s.PERMISSION_ID);

COMMIT;
