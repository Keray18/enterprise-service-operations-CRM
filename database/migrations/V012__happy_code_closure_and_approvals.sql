-- 4. Create CUSTOMER_FEEDBACK Table
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'CUSTOMER_FEEDBACK';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE CUSTOMER_FEEDBACK (
            FEEDBACK_ID         VARCHAR2(36 CHAR) PRIMARY KEY,
            REQUEST_ID          VARCHAR2(36 CHAR) NOT NULL REFERENCES SERVICE_REQUESTS(REQUEST_ID),
            RATING              NUMBER(1,0) NOT NULL CHECK (RATING BETWEEN 1 AND 5),
            FEEDBACK_REMARKS    VARCHAR2(1000 CHAR),
            QUALITY_ANALYSIS    VARCHAR2(1000 CHAR),
            SUBMITTED_BY        VARCHAR2(36 CHAR) REFERENCES APP_USERS(USER_ID),
            SUBMITTED_AT        TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            CREATED_AT          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT UQ_FEEDBACK_REQUEST UNIQUE (REQUEST_ID)
        )';
    END IF;
END;
/

-- 5. Create REPLACEMENT_REQUESTS Table
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'REPLACEMENT_REQUESTS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE REPLACEMENT_REQUESTS (
            REPLACEMENT_ID      VARCHAR2(36 CHAR) PRIMARY KEY,
            REQUEST_ID          VARCHAR2(36 CHAR) NOT NULL REFERENCES SERVICE_REQUESTS(REQUEST_ID),
            REASON_CODE         VARCHAR2(30 CHAR) NOT NULL,
            REASON_DESCRIPTION  VARCHAR2(500 CHAR) NOT NULL,
            TECHNICIAN_REMARKS  VARCHAR2(1000 CHAR),
            STATUS              VARCHAR2(20 CHAR) DEFAULT ''PENDING'' NOT NULL CHECK (STATUS IN (''PENDING'', ''APPROVED'', ''REJECTED'')),
            APPROVAL_NUMBER     VARCHAR2(50 CHAR) UNIQUE,
            REQUESTED_BY        VARCHAR2(36 CHAR) NOT NULL REFERENCES APP_USERS(USER_ID),
            REQUESTED_AT        TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            REVIEWED_BY         VARCHAR2(36 CHAR) REFERENCES APP_USERS(USER_ID),
            REVIEWED_AT         TIMESTAMP(6) WITH TIME ZONE,
            REVIEW_REMARKS      VARCHAR2(1000 CHAR),
            CREATED_AT          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
        )';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_RR_REQUEST_ID ON REPLACEMENT_REQUESTS (REQUEST_ID)';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_RR_STATUS ON REPLACEMENT_REQUESTS (STATUS)';
    END IF;
END;
