-- 1. Update CK_SR_STATUS Constraint to Include REPLACEMENT_APPROVED
DECLARE
    v_count NUMBER;
BEGIN
    FOR r IN (
        SELECT constraint_name 
        FROM user_constraints 
        WHERE table_name = 'SERVICE_REQUESTS' 
          AND constraint_type = 'C' 
          AND search_condition_vc LIKE '%STATUS IN%'
    ) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE SERVICE_REQUESTS DROP CONSTRAINT ' || r.constraint_name;
    END LOOP;

    EXECUTE IMMEDIATE 'ALTER TABLE SERVICE_REQUESTS ADD CONSTRAINT CK_SR_STATUS CHECK (
        STATUS IN (
            ''REGISTERED'',
            ''ASSIGNED_TO_ASF'',
            ''ACKNOWLEDGED'',
            ''APPOINTMENT_SCHEDULED'',
            ''TECHNICIAN_CHECKED_IN'',
            ''IN_PROGRESS_REPAIR'',
            ''PENDING_SPARE_PART'',
            ''PENDING_SPECIAL_PART_ESTIMATE'',
            ''SPECIAL_PART_ESTIMATE_PROVIDED'',
            ''REQUEST_FOR_REPLACEMENT'',
            ''REPLACEMENT_APPROVED'',
            ''REQUEST_FOR_CANCELLATION'',
            ''CALL_CLOSURE_SUBMITTED'',
            ''CLOSED'',
            ''CANCELLED'',
            ''REPLACED''
        )
    )';
END;
/

-- 2. Add Closure, Cancellation & Approval Columns to SERVICE_REQUESTS
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tab_cols WHERE table_name = 'SERVICE_REQUESTS' AND column_name = 'REPLACEMENT_APPROVAL_NO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE SERVICE_REQUESTS ADD (
            REPLACEMENT_APPROVAL_NO         VARCHAR2(50 CHAR),
            CLOSED_AT                       TIMESTAMP(6) WITH TIME ZONE,
            CLOSED_BY                       VARCHAR2(36 CHAR) REFERENCES APP_USERS(USER_ID),
            CANCELLED_AT                    TIMESTAMP(6) WITH TIME ZONE,
            CANCELLED_BY                    VARCHAR2(36 CHAR) REFERENCES APP_USERS(USER_ID),
            SUPERVISOR_OVERRIDE_REASON      VARCHAR2(1000 CHAR)
        )';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_SR_REP_APP_NO ON SERVICE_REQUESTS (REPLACEMENT_APPROVAL_NO)';
    END IF;
END;
/

