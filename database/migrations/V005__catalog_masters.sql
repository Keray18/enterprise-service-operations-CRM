    CREATED_BY                  VARCHAR2(100 CHAR),
    UPDATED_BY                  VARCHAR2(100 CHAR),
    CONSTRAINT UQ_MODELS_BRAND_CODE UNIQUE (BRAND_ID, MODEL_CODE)
