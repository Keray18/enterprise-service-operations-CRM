    AUDIT_ID                VARCHAR2(36 CHAR) PRIMARY KEY,
    ENTITY_NAME             VARCHAR2(50 CHAR) NOT NULL CHECK (ENTITY_NAME IN ('BRAND', 'PRODUCT', 'MODEL')),
    ENTITY_ID               VARCHAR2(36 CHAR) NOT NULL,
    ACTION                  VARCHAR2(30 CHAR) NOT NULL CHECK (ACTION IN ('CREATE', 'UPDATE', 'ACTIVATE', 'DEACTIVATE')),
    PERFORMED_BY            VARCHAR2(36 CHAR) NOT NULL,
    PERFORMED_BY_USERNAME   VARCHAR2(50 CHAR) NOT NULL,
    CHANGES_JSON            CLOB,
