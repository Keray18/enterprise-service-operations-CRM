-- P0: Location Master Data Hygiene, Test Fixture Classification, and Operational Scoping

-- 1. Add IS_TEST_FIXTURE and DATA_ORIGIN columns to LOCATIONS table
ALTER TABLE LOCATIONS ADD (
    IS_TEST_FIXTURE CHAR(1 CHAR) DEFAULT 'N' NOT NULL CHECK (IS_TEST_FIXTURE IN ('Y', 'N')),
    DATA_ORIGIN VARCHAR2(30 CHAR) DEFAULT 'OPERATIONAL' NOT NULL
);

-- 2. Create index on test fixture and party type for high-performance operational filtering
CREATE INDEX IDX_LOCATIONS_FIXTURE ON LOCATIONS (IS_TEST_FIXTURE, PARTY_TYPE, IS_ACTIVE);

-- 3. Classify baseline operational locations
UPDATE LOCATIONS
SET DATA_ORIGIN = 'SYSTEM_MIGRATION',
    IS_TEST_FIXTURE = 'N'
WHERE CREATED_BY = 'SYSTEM_MIGRATION'
   OR LOCATION_CODE IN ('WH-CENTRAL', 'ASF-MUM-01');

UPDATE LOCATIONS
SET DATA_ORIGIN = 'OPERATIONAL',
    IS_TEST_FIXTURE = 'N'
WHERE CREATED_BY = 'SETUP';

UPDATE LOCATIONS
SET DATA_ORIGIN = 'DELHI_NCR_SEED',
    IS_TEST_FIXTURE = 'N'
WHERE CREATED_BY = 'DELHI_NCR_SEED';

-- 4. Classify confirmed automated test fixtures
UPDATE LOCATIONS
SET IS_TEST_FIXTURE = 'Y',
    DATA_ORIGIN = 'TEST_FIXTURE'
WHERE CREATED_BY = 'TEST_SETUP'
   OR UPPER(LOCATION_CODE) LIKE '%TEST%'
   OR LOCATION_CODE LIKE 'SEC_%'
   OR LOCATION_CODE LIKE 'ASF_360_%'
   OR LOCATION_CODE LIKE 'ASF_OTH_%'
   OR LOCATION_CODE LIKE 'ASF_2C_%'
   OR LOCATION_CODE LIKE 'ASF_UAT_%'
   OR LOCATION_CODE LIKE 'WH_UAT_%'
   OR LOCATION_CODE LIKE 'ASF1_%'
   OR LOCATION_CODE LIKE 'ASF2_%'
   OR REGEXP_LIKE(LOCATION_CODE, '_(MV|MW)[0-9A-Z]{6,}');

COMMIT;

