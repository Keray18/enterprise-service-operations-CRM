-- 9. Seed Granular Inventory Permissions & Role Associations
MERGE INTO PERMISSIONS p
USING (SELECT '10000000-0000-0000-0000-000000000040' AS PERMISSION_ID, 'inventory:adjust' AS CODE, 'WAREHOUSE' AS MODULE, 'Perform controlled inventory write-offs and quantity adjustments' AS DESCRIPTION FROM DUAL) s
ON (p.CODE = s.CODE)
WHEN NOT MATCHED THEN INSERT (PERMISSION_ID, CODE, MODULE, DESCRIPTION) VALUES (s.PERMISSION_ID, s.CODE, s.MODULE, s.DESCRIPTION);

MERGE INTO PERMISSIONS p
USING (SELECT '10000000-0000-0000-0000-000000000041' AS PERMISSION_ID, 'inventory:reconcile' AS CODE, 'WAREHOUSE' AS MODULE, 'Execute inventory reconciliation checks against immutable movement ledgers' AS DESCRIPTION FROM DUAL) s
ON (p.CODE = s.CODE)
WHEN NOT MATCHED THEN INSERT (PERMISSION_ID, CODE, MODULE, DESCRIPTION) VALUES (s.PERMISSION_ID, s.CODE, s.MODULE, s.DESCRIPTION);

MERGE INTO PERMISSIONS p
USING (SELECT '10000000-0000-0000-0000-000000000042' AS PERMISSION_ID, 'inventory:transfer' AS CODE, 'WAREHOUSE' AS MODULE, 'Acknowledge inter-facility transfers and in-transit shipments' AS DESCRIPTION FROM DUAL) s
ON (p.CODE = s.CODE)
WHEN NOT MATCHED THEN INSERT (PERMISSION_ID, CODE, MODULE, DESCRIPTION) VALUES (s.PERMISSION_ID, s.CODE, s.MODULE, s.DESCRIPTION);

-- Assign inventory:adjust and inventory:reconcile to ADMIN and WAREHOUSE
MERGE INTO ROLE_PERMISSIONS rp
USING (
    SELECT r.ROLE_ID, p.PERMISSION_ID
    FROM ROLES r
    CROSS JOIN PERMISSIONS p
    WHERE r.CODE IN ('ADMIN', 'WAREHOUSE')
      AND p.CODE IN ('inventory:adjust', 'inventory:reconcile', 'inventory:transfer')
) s
ON (rp.ROLE_ID = s.ROLE_ID AND rp.PERMISSION_ID = s.PERMISSION_ID)
WHEN NOT MATCHED THEN INSERT (ROLE_ID, PERMISSION_ID) VALUES (s.ROLE_ID, s.PERMISSION_ID);

-- Also assign inventory:transfer to ASF so ASF can acknowledge received shipments
MERGE INTO ROLE_PERMISSIONS rp
USING (
    SELECT r.ROLE_ID, p.PERMISSION_ID
    FROM ROLES r
    CROSS JOIN PERMISSIONS p
    WHERE r.CODE = 'ASF'
      AND p.CODE = 'inventory:transfer'
) s
ON (rp.ROLE_ID = s.ROLE_ID AND rp.PERMISSION_ID = s.PERMISSION_ID)
WHEN NOT MATCHED THEN INSERT (ROLE_ID, PERMISSION_ID) VALUES (s.ROLE_ID, s.PERMISSION_ID);

-- 10. Seed Initial Central Warehouse Location and Stock Balances if not present
DECLARE
    v_wh_id VARCHAR2(36 CHAR) := '00000000-0000-0000-0008-000000000001';
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM LOCATIONS WHERE LOCATION_ID = v_wh_id OR LOCATION_CODE = 'WH-CENTRAL';
    IF v_count = 0 THEN
        INSERT INTO LOCATIONS (LOCATION_ID, LOCATION_CODE, LOCATION_NAME, PARTY_TYPE, IS_ACTIVE, CREATED_BY)
        VALUES (v_wh_id, 'WH-CENTRAL', 'Central Logistics Warehouse (Bhiwandi)', 'CENTRAL_WAREHOUSE', 'Y', 'SYSTEM_MIGRATION');
    ELSE
        SELECT LOCATION_ID INTO v_wh_id FROM LOCATIONS WHERE LOCATION_CODE = 'WH-CENTRAL' AND ROWNUM = 1;
    END IF;

    -- Seed baseline inventory balances for existing parts at Central Warehouse
    FOR p IN (SELECT PART_ID FROM PART_CODES WHERE IS_ACTIVE = 'Y') LOOP
        SELECT COUNT(*) INTO v_count FROM INVENTORY_BALANCES WHERE LOCATION_ID = v_wh_id AND PART_ID = p.PART_ID;
        IF v_count = 0 THEN
            INSERT INTO INVENTORY_BALANCES (
                BALANCE_ID, LOCATION_ID, PART_ID, QTY_ON_HAND, QTY_RESERVED, QTY_IN_TRANSIT, QTY_DEFECTIVE, REORDER_LEVEL, CREATED_AT, UPDATED_AT
            ) VALUES (
                SYS_GUID(), v_wh_id, p.PART_ID, 50, 0, 0, 0, 10, SYSTIMESTAMP, SYSTIMESTAMP
            );

            -- Initial movement record
            INSERT INTO INVENTORY_MOVEMENTS (
                MOVEMENT_ID, LOCATION_ID, PART_ID, MOVEMENT_TYPE, STOCK_BUCKET, QUANTITY,
                BALANCE_BEFORE, BALANCE_AFTER, REFERENCE_TYPE, REFERENCE_ID, ACTOR_USERNAME, REMARKS, CREATED_AT
            ) VALUES (
                SYS_GUID(), v_wh_id, p.PART_ID, 'GRN_RECEIPT', 'ON_HAND', 50,
                0, 50, 'OPENING_BALANCE', 'INIT-2026', 'SYSTEM_MIGRATION', 'Initial stock seed at Central Warehouse', SYSTIMESTAMP
            );
        END IF;
    END LOOP;
END;
