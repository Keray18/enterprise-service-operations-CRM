-- 2. CUSTOMERS Table
CREATE TABLE CUSTOMERS (
    CUSTOMER_ID         VARCHAR2(36 CHAR) PRIMARY KEY,
    CUSTOMER_CODE       VARCHAR2(30 CHAR) NOT NULL,
    FULL_NAME           VARCHAR2(150 CHAR) NOT NULL,
    PRIMARY_MOBILE      VARCHAR2(20 CHAR) NOT NULL,
    NORMALIZED_MOBILE   VARCHAR2(15 CHAR) NOT NULL,
    ALTERNATE_MOBILE    VARCHAR2(20 CHAR),
    RESIDENCE_PHONE     VARCHAR2(20 CHAR),
    EMAIL               VARCHAR2(150 CHAR),
    CUSTOMER_CATEGORY   VARCHAR2(50 CHAR) DEFAULT 'INDIVIDUAL' NOT NULL CHECK (CUSTOMER_CATEGORY IN ('INDIVIDUAL', 'COMMERCIAL', 'CORPORATE')),
    ADDRESS_LINE        VARCHAR2(255 CHAR) NOT NULL,
    LANDMARK            VARCHAR2(150 CHAR),
    STATE_ID            VARCHAR2(36 CHAR) NOT NULL REFERENCES STATES(STATE_ID),
    CITY_ID             VARCHAR2(36 CHAR) NOT NULL REFERENCES CITIES(CITY_ID),
    PINCODE             VARCHAR2(10 CHAR) NOT NULL,
    GST_NUMBER          VARCHAR2(20 CHAR),
    IS_ACTIVE           CHAR(1 CHAR) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y', 'N')),
    VERSION_NO          NUMBER(10,0) DEFAULT 1 NOT NULL,
    CREATED_AT          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY          VARCHAR2(100 CHAR),
    UPDATED_BY          VARCHAR2(100 CHAR),
    CONSTRAINT UQ_CUSTOMERS_CODE UNIQUE (CUSTOMER_CODE)
);

CREATE INDEX IDX_CUSTOMERS_NORM_MOBILE ON CUSTOMERS (NORMALIZED_MOBILE);
CREATE INDEX IDX_CUSTOMERS_PRIMARY_MOBILE ON CUSTOMERS (PRIMARY_MOBILE);
CREATE INDEX IDX_CUSTOMERS_FULL_NAME ON CUSTOMERS (LOWER(FULL_NAME));
CREATE INDEX IDX_CUSTOMERS_PINCODE ON CUSTOMERS (PINCODE);
CREATE INDEX IDX_CUSTOMERS_IS_ACTIVE ON CUSTOMERS (IS_ACTIVE);

