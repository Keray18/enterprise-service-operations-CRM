-- 5. SERVICE_REQUESTS Table (Central Operations Entity)
CREATE TABLE SERVICE_REQUESTS (
    REQUEST_ID              VARCHAR2(36 CHAR) PRIMARY KEY,
    JOB_NUMBER              VARCHAR2(40 CHAR) NOT NULL,
    CUSTOMER_ID             VARCHAR2(36 CHAR) NOT NULL REFERENCES CUSTOMERS(CUSTOMER_ID),
    BRAND_ID                VARCHAR2(36 CHAR) NOT NULL REFERENCES BRANDS(BRAND_ID),
    PRODUCT_ID              VARCHAR2(36 CHAR) NOT NULL REFERENCES PRODUCTS(PRODUCT_ID),
    MODEL_ID                VARCHAR2(36 CHAR) NOT NULL REFERENCES MODELS(MODEL_ID),
    SERIAL_NUMBER           VARCHAR2(60 CHAR),
    PURCHASE_DATE           DATE,
    INVOICE_NO              VARCHAR2(50 CHAR),
    DEALER_NAME             VARCHAR2(150 CHAR),
    CALL_TYPE               VARCHAR2(30 CHAR) NOT NULL CHECK (CALL_TYPE IN ('REPAIR', 'INSTALLATION', 'DEMO', 'MAINTENANCE')),
    SERVICE_TYPE            VARCHAR2(30 CHAR) DEFAULT 'ON_SITE' NOT NULL CHECK (SERVICE_TYPE IN ('ON_SITE', 'CARRY_IN', 'PICK_UP')),
    STATUS                  VARCHAR2(50 CHAR) DEFAULT 'REGISTERED' NOT NULL CHECK (STATUS IN ('REGISTERED', 'ASSIGNED_TO_ASF', 'ACKNOWLEDGED', 'APPOINTMENT_SCHEDULED', 'TECHNICIAN_CHECKED_IN', 'IN_PROGRESS_REPAIR', 'PENDING_SPARE_PART', 'CALL_CLOSURE_SUBMITTED', 'CLOSED', 'CANCELLED', 'REPLACED')),
    WARRANTY_STATUS         VARCHAR2(30 CHAR) DEFAULT 'UNDER_VERIFICATION' NOT NULL CHECK (WARRANTY_STATUS IN ('IN_WARRANTY', 'OUT_OF_WARRANTY', 'UNDER_VERIFICATION', 'AMC', 'VOID')),
    ASSIGNED_LOCATION_ID    VARCHAR2(36 CHAR) REFERENCES LOCATIONS(LOCATION_ID),
    ASSIGNED_ENGINEER_ID    VARCHAR2(36 CHAR) REFERENCES APP_USERS(USER_ID),
    VOC_ID                  VARCHAR2(36 CHAR) REFERENCES VOC_MASTERS(VOC_ID),
    VOC_DESCRIPTION         VARCHAR2(255 CHAR),
    PROBLEM_DESCRIPTION     VARCHAR2(1000 CHAR),
    CUSTOMER_ADDRESS        VARCHAR2(255 CHAR),
    CUSTOMER_PINCODE        VARCHAR2(10 CHAR),
    CUSTOMER_STATE_ID       VARCHAR2(36 CHAR) REFERENCES STATES(STATE_ID),
    CUSTOMER_CITY_ID        VARCHAR2(36 CHAR) REFERENCES CITIES(CITY_ID),
    CUSTOMER_PHONE          VARCHAR2(20 CHAR),
    REGISTERED_BY           VARCHAR2(36 CHAR) REFERENCES APP_USERS(USER_ID),
    REGISTERED_BY_USERNAME  VARCHAR2(100 CHAR),
    REGISTERED_AT           TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    SLA_48H_EXPIRES_AT      TIMESTAMP(6) WITH TIME ZONE,
    IDEMPOTENCY_KEY         VARCHAR2(100 CHAR),
    VERSION_NO              NUMBER(10,0) DEFAULT 1 NOT NULL,
    CREATED_AT              TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT              TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_SR_JOB_NUMBER UNIQUE (JOB_NUMBER),
    CONSTRAINT UQ_SR_IDEMPOTENCY UNIQUE (IDEMPOTENCY_KEY)
);

CREATE INDEX IDX_SR_CUSTOMER_ID ON SERVICE_REQUESTS (CUSTOMER_ID);
CREATE INDEX IDX_SR_STATUS ON SERVICE_REQUESTS (STATUS);
CREATE INDEX IDX_SR_SERIAL_NUMBER ON SERVICE_REQUESTS (SERIAL_NUMBER);
CREATE INDEX IDX_SR_REGISTERED_AT ON SERVICE_REQUESTS (REGISTERED_AT DESC);
CREATE INDEX IDX_SR_LOCATION_ID ON SERVICE_REQUESTS (ASSIGNED_LOCATION_ID);
CREATE INDEX IDX_SR_MODEL_ID ON SERVICE_REQUESTS (MODEL_ID);

-- 6. SERVICE_REQUEST_EVENTS Table (Immutable Transition History)
CREATE TABLE SERVICE_REQUEST_EVENTS (
    EVENT_ID                VARCHAR2(36 CHAR) PRIMARY KEY,
    REQUEST_ID              VARCHAR2(36 CHAR) NOT NULL REFERENCES SERVICE_REQUESTS(REQUEST_ID),
    FROM_STATE              VARCHAR2(50 CHAR) DEFAULT 'NONE' NOT NULL,
    TO_STATE                VARCHAR2(50 CHAR) NOT NULL,
    EVENT_TYPE              VARCHAR2(50 CHAR) DEFAULT 'CALL_REGISTERED' NOT NULL,
    TRIGGERED_BY_USER_ID    VARCHAR2(36 CHAR) NOT NULL REFERENCES APP_USERS(USER_ID),
    TRIGGERED_BY_USERNAME   VARCHAR2(100 CHAR) NOT NULL,
    TRIGGERED_BY_ROLE       VARCHAR2(50 CHAR) NOT NULL,
    REMARKS                 VARCHAR2(1000 CHAR),
    METADATA_JSON           CLOB CHECK (METADATA_JSON IS JSON),
    CREATED_AT              TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_SRE_REQUEST_ID ON SERVICE_REQUEST_EVENTS (REQUEST_ID);
CREATE INDEX IDX_SRE_CREATED_AT ON SERVICE_REQUEST_EVENTS (CREATED_AT DESC);

-- 7. NOTIFICATIONS_OUTBOX Table (Transactional Messaging Outbox)
CREATE TABLE NOTIFICATIONS_OUTBOX (
    NOTIFICATION_ID         VARCHAR2(36 CHAR) PRIMARY KEY,
    REQUEST_ID              VARCHAR2(36 CHAR) REFERENCES SERVICE_REQUESTS(REQUEST_ID),
    CHANNEL                 VARCHAR2(20 CHAR) DEFAULT 'SMS' NOT NULL CHECK (CHANNEL IN ('SMS', 'EMAIL', 'WHATSAPP')),
    RECIPIENT               VARCHAR2(100 CHAR) NOT NULL,
    TEMPLATE_CODE           VARCHAR2(50 CHAR) DEFAULT 'SMS_1_REGISTRATION' NOT NULL,
    MESSAGE_BODY            VARCHAR2(1000 CHAR) NOT NULL,
    STATUS                  VARCHAR2(20 CHAR) DEFAULT 'QUEUED' NOT NULL CHECK (STATUS IN ('QUEUED', 'SENT', 'FAILED')),
    PROVIDER_MESSAGE_ID     VARCHAR2(100 CHAR),
    ERROR_MESSAGE           VARCHAR2(500 CHAR),
    RETRY_COUNT             NUMBER(3,0) DEFAULT 0 NOT NULL,
    SENT_AT                 TIMESTAMP(6) WITH TIME ZONE,
    CREATED_AT              TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_NOTIF_REQUEST_ID ON NOTIFICATIONS_OUTBOX (REQUEST_ID);
CREATE INDEX IDX_NOTIF_STATUS ON NOTIFICATIONS_OUTBOX (STATUS);
CREATE INDEX IDX_NOTIF_CREATED_AT ON NOTIFICATIONS_OUTBOX (CREATED_AT DESC);

