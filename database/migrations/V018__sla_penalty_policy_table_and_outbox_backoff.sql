    SELECT COUNT(*) INTO v_col_count FROM user_tab_cols
    WHERE table_name = 'NOTIFICATIONS_OUTBOX' AND column_name = 'UPDATED_AT';

    IF v_col_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE NOTIFICATIONS_OUTBOX ADD (UPDATED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL)';
    END IF;
END;
