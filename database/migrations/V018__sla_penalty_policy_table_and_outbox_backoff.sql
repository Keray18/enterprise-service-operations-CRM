-- 2. Add UQ_SLA_PENALTY_BREACH Constraint to SLA_PENALTY_RECORDS
DECLARE
    v_uq_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_uq_count FROM user_constraints
    WHERE constraint_name = 'UQ_SLA_PENALTY_BREACH' AND table_name = 'SLA_PENALTY_RECORDS';

