-- 4. Update NOTIFICATIONS_OUTBOX Status Check Constraint
DECLARE
    v_chk_name VARCHAR2(100);
BEGIN
    -- Find existing status check constraint on NOTIFICATIONS_OUTBOX
    FOR c IN (
        SELECT uc.CONSTRAINT_NAME 
        FROM user_constraints uc
        JOIN user_cons_columns ucc ON uc.CONSTRAINT_NAME = ucc.CONSTRAINT_NAME
        WHERE uc.TABLE_NAME = 'NOTIFICATIONS_OUTBOX' 
          AND uc.CONSTRAINT_TYPE = 'C' 
          AND ucc.COLUMN_NAME = 'STATUS'
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'ALTER TABLE NOTIFICATIONS_OUTBOX DROP CONSTRAINT ' || c.CONSTRAINT_NAME;
        EXCEPTION WHEN OTHERS THEN NULL;
        END;
    END LOOP;

    EXECUTE IMMEDIATE 'ALTER TABLE NOTIFICATIONS_OUTBOX ADD CONSTRAINT CHK_NOTIF_STATUS CHECK (STATUS IN (''QUEUED'', ''PROCESSING'', ''SENT'', ''FAILED'', ''DEAD_LETTER''))';
END;
